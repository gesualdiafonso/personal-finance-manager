#!/usr/bin/env node
/**
 * Generates src/lib/supabase/types.ts (the `Database` type for the Supabase clients) from a LOCAL
 * reference database built with database/tests/supabase-emulation.sql + database/sql/01–07.
 * Same shape as `supabase gen types typescript`; once the project exists, that command can
 * replace this script. Never reads from Supabase.
 *
 * Usage: PGHOST=/tmp/pgtest PGPORT=55432 node scripts/db/generate-types.mjs aureon_ref
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const db = process.argv[2] ?? "aureon_ref";
if (/supabase/i.test(process.env.PGHOST ?? "")) {
  console.error("Refusing: PGHOST looks like Supabase. Use a local reference database.");
  process.exit(2);
}
const rows = execFileSync(
  "psql",
  ["-U", process.env.PGUSER ?? "postgres", "-d", db, "-At", "-F", "\t", "-X", "-c", `
    select c.relname, a.attname, t.typname, bt.typname, a.attnotnull, a.atthasdef or a.attidentity <> '', a.attndims > 0 or t.typcategory = 'A',
           coalesce(et.typname, ''), coalesce(ebt.typname, '')
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_type t on t.oid = a.atttypid
    left join pg_type bt on bt.oid = t.typbasetype
    left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
    left join pg_type ebt on ebt.oid = et.typbasetype
    where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
    order by c.relname, a.attnum`],
  { encoding: "utf8" },
)
  .trim()
  .split("\n")
  .map((l) => l.split("\t"));

const CURRENCY = `"ARS" | "USD" | "EUR" | "BRL" | "UYU" | "CLP" | "PYG" | "GBP"`;
function tsType(typ, base, isArray, elem, elemBase) {
  if (isArray === "t") return `${tsType(elem, elemBase, "f")}[]`;
  if (typ === "currency_code") return CURRENCY;
  const t = base || typ;
  if (["int2", "int4", "int8", "numeric", "float4", "float8"].includes(t)) return "number";
  if (t === "bool") return "boolean";
  if (["json", "jsonb"].includes(t)) return "Json";
  return "string"; // uuid, text, date, timestamptz
}

const tables = new Map();
for (const [table, column, typ, base, notNull, hasDefault, isArray, elem, elemBase] of rows) {
  if (!tables.has(table)) tables.set(table, []);
  tables.get(table).push({ column, type: tsType(typ, base, isArray, elem, elemBase), notNull: notNull === "t", hasDefault: hasDefault === "t" });
}

const block = (cols, mode) =>
  cols
    .map(({ column, type, notNull, hasDefault }) => {
      const nullable = notNull ? "" : " | null";
      const optional = mode === "Update" || (mode === "Insert" && (!notNull || hasDefault)) ? "?" : "";
      return `          ${column}${optional}: ${type}${nullable};`;
    })
    .join("\n");

const out = `/**
 * Database types for the Supabase clients — GENERATED by scripts/db/generate-types.mjs from the
 * schema in database/sql (validated on a local PostgreSQL; ${new Date().toISOString().slice(0, 10)}).
 * Do not edit by hand. When the Supabase project exists, \`supabase gen types typescript\` produces
 * the same shape and may replace this file.
 *
 * Notes (docs/database/TYPESCRIPT-POSTGRES-MAPPING.md):
 * - bigint money columns (public.money_minor) are typed as number: every value is within
 *   Number.MAX_SAFE_INTEGER (enforced by the domain).
 * - Exchange rates are TEXT on purpose (exact decimals; never a JS float).
 * - Every table has RLS enabled and NO policies until Step 15: queries from the browser return
 *   "permission denied" until then.
 */
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export interface Database {
  public: {
    Tables: {
${[...tables.entries()]
  .map(
    ([name, cols]) => `      ${name}: {
        Row: {
${block(cols, "Row")}
        };
        Insert: {
${block(cols, "Insert")}
        };
        Update: {
${block(cols, "Update")}
        };
        Relationships: [];
      };`,
  )
  .join("\n")}
    };
    Views: Record<string, never>;
    Functions: Record<string, never>;
    Enums: Record<string, never>;
    CompositeTypes: Record<string, never>;
  };
}

/** Names of the AUREON tables (same list as database/sql/08_verification.sql). */
export const DATABASE_TABLES = ${JSON.stringify([...tables.keys()])} as const;
export type TableName = (typeof DATABASE_TABLES)[number];
export type TableRow<T extends TableName> = Database["public"]["Tables"][T]["Row"];
`;
writeFileSync(resolve("src/lib/supabase/types.ts"), out);
console.log(`types.ts: ${tables.size} tables, ${rows.length} columns`);
